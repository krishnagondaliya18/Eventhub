async function run() {
  try {
    console.log('Connecting to MongoDB...');
    await mongoose.connect(process.env.MONGODB_URI);
    console.log('Connected to MongoDB.');

    // Find or create admin user for organizer field
    let admin = await User.findOne({ role: 'admin' });
    if (!admin) {
      console.log('Admin not found, creating admin user...');
      admin = await User.create({
        name: 'Admin User',
        email: 'admin@eventhub.com',
        password: 'admin123',
        role: 'admin',
        phone: '9999999999'
      });
    }

    console.log(`Using admin organizer: ${admin.email} (${admin._id})`);

    // Verify EVERY event has a valid photo URL
    const missingPhotos = allEvents.filter(e => !e.image || e.image.trim() === '');
    if (missingPhotos.length > 0) {
      throw new Error(`CRITICAL: Found ${missingPhotos.length} events without photo! Aborting.`);
    }

    console.log(`Verified: All ${allEvents.length} events have valid high-resolution photo URLs.`);

    // Attach organizer ID to every event
    const eventsWithOrganizer = allEvents.map(e => ({
      ...e,
      organizer: admin._id
    }));

    // Clear existing events and insert the complete 78 premium events
    console.log('Refreshing EventHub database with complete catalog...');
    await Event.deleteMany({});
    
    const inserted = await Event.insertMany(eventsWithOrganizer);
    console.log(`SUCCESS: Successfully inserted ${inserted.length} events into EventHub database!`);

    // Verification check directly in DB
    const totalCount = await Event.countDocuments();
    const noPhotoCount = await Event.countDocuments({
      $or: [
        { image: { $exists: false } },
        { image: null },
        { image: '' }
      ]
    });

    console.log(`\n================ DATABASE REPORT ================`);
    console.log(`Total Events in DB   : ${totalCount}`);
    console.log(`Events without photo : ${noPhotoCount}`);
    console.log(`All events with photo: ${noPhotoCount === 0 ? 'YES (100%)' : 'NO'}`);
    console.log(`=================================================`);

    process.exit(0);
  } catch (err) {
    console.error('Error populating events:', err);
    process.exit(1);
  }
}

run();
